const HtmlWebpackPlugin = require('html-webpack-plugin');
const CopyPlugin = require('copy-webpack-plugin');
const TsConfigPathsPlugin = require('tsconfig-paths-webpack-plugin');

module.exports = {
  mode: 'development',
  output: {
    publicPath: '/',
    clean: true,
  },

  devServer: {
    // Serve index.html for client-side routes like /draft
    historyApiFallback: true,
    // Live stream of the lobby must not be compressed or buffered
    compress: false,
    // `npm run dev` + `npm run dev:server`: lobby API of the second process
    proxy: {
      '/api': 'http://localhost:8081',
    },
  },
  resolve: {
    extensions: ['.tsx', '.ts', '.js'],
    plugins: [new TsConfigPathsPlugin()],
  },
  module: {
    rules: [
      {
        test: /\.(ts|tsx)$/,
        loader: 'ts-loader',
        // Type errors in inherited WarYes code must not block the build
        options: {transpileOnly: true},
      },
      {
        test: /\.css$/,
        use: ['style-loader', 'css-loader'],
      },
      {
        test: /\.(png|svg|jpg|jpeg|gif|webp)$/,
        type: 'asset/resource',
      },
    ],
  },

  plugins: [
    new HtmlWebpackPlugin({template: './src/index.html', hash: true, publicPath: '/'}),
    // Static hosts without SPA routing (e.g. GitHub Pages) serve 404.html for /draft
    new HtmlWebpackPlugin({template: './src/index.html', hash: true, publicPath: '/', filename: '404.html'}),
    new CopyPlugin({
      patterns: [
        {from: 'site-meta', to: '.', globOptions: {dot: true}},
        {from: 'images/units', to: 'images/units/'},
        {from: 'images/weapons', to: 'images/weapons/'},
        {from: 'stats-toolkit', to: 'stats-toolkit/'},
        // Game data generated by tools/wif-extractor (wif.json, vanilla.json)
        // and the vanilla DLC list (vanilla-dlc.json)
        {from: 'data/*.json', to: 'data/[name][ext]', globOptions: {ignore: ['**/*-report.json']}, noErrorOnMissing: true},
      ],
    }),
  ],
};
